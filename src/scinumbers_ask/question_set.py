"""The question set: what is asked, which entries should support it, what it exercises.

One JSON object per line (ADR-0220), read by the evaluation harness and never
generated by the system under test -- a set the agent wrote is a set the agent
passes. The file is the reference the whole evaluation is scored against, so the
loader is strict rather than forgiving: a set that loads is one every score can be
computed from, and a set that cannot be is a message naming the line and the fix.

**Which direction the strictness runs, and why.** Every rule here refuses a set
rather than repairing it, because each repair would be silent at exactly the moment
it mattered. An unknown key is rejected, not ignored: `expected_entires` ignored
leaves a question with no expected entries, which scores as the agent citing
nothing expected -- a perfect run reported as a total failure, or the reverse, with
nothing anywhere saying why. A quoted identifier is rejected rather than coerced,
because `"113525"` never equals the `113525` the citation parser produces and the
comparison would fail forever, quietly. The cost of the strict direction is a
person editing one line; the cost of the lenient one is a figure nobody can trust.

Entry identifiers are integers here because they are integers everywhere else --
`Entry.entry_id`, `citations()` and `AnswerEntries.cited` all carry `int` -- and a
set that recorded them as strings would compare unequal to every citation.

**The invariants live on `Question`, not only in the reader.** Groups 3 to 6 build
`Question` objects in tests and fixtures, and one built with neither an unsupported
flag nor expected entries scores as "cited 0 of 0 expected", which reads as a pass.
So the type refuses it too. The reader's own checks stay because they can say which
line and which key; the type's exist because the reader is not the only caller.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from enum import StrEnum
from pathlib import Path

from .corpus import Entry
from .repository import CorpusRepository
from .units import dimension


class QuestionSetError(Exception):
    """A question set that cannot be scored against, and what to do about it."""


class Tier(StrEnum):
    """What a question demands of the agent, so a gain in one kind is not paid for
    out of another.

    The report gives its figures per tier because the tiers fail differently and
    the trade between them is real: a prompt that makes the agent search harder for
    a comparison can easily cost it precision on the single-property questions that
    are most of what anyone asks. A headline averaged over all three hides exactly
    that.

    **A closed vocabulary, unlike `tags`.** Tags are free-form because the report
    merely groups by them; a tier is compared against the same tier in an earlier
    run, and a typo would silently open a fourth bucket with one question in it and
    leave the one it should have joined looking improved.
    """

    #: One property, one organism, answered from what was retrieved.
    BASIC = "basic"
    #: More than one organism or property, a figure that has to be computed, or a
    #: follow-up that depends on what an earlier question established.
    COMPOUND = "compound"
    #: The corpus cannot answer it as asked -- absent organism, or a false premise.
    #: Scored on whether the agent declines rather than on what it brings back.
    DECLINING = "declining"


@dataclass(frozen=True)
class Question:
    """One question, its expected support, and what it is in the set to exercise."""

    question_id: str
    question: str
    # Plural because a comparison asks about more than one. "Is an E. coli cell
    # bigger than a yeast cell?" is one question about two organisms; the spec
    # names a comparison across entries as a tag the set carries, and task 2.1 asks
    # for a volume asked of two different objects. With one term per question, a
    # perfect answer to such a question would score at most half on "the fraction
    # of cited entries carrying the asked organism".
    #
    # In the corpus's own vocabulary, so the score uses the repository's resolution
    # and not a paraphrase. Required even for an unsupported question: the terms are
    # what it asks about, and that they resolve to nothing is the point of it.
    asked_properties: tuple[str, ...]
    asked_organisms: tuple[str, ...]
    expected_entries: tuple[int, ...] = ()
    # Entries recording a *different* property that nonetheless answers the
    # question -- the nucleoid where a bacterium was asked for a nucleus, a radius
    # where a volume was asked for. Citing one is not unexpected and not citing one
    # is not a miss; the list exists so that `unexpected` means something (ADR-0530).
    #
    # Unlike `expected_entries` this is **not** copied into a result record. It is
    # read from the set at report time, because borderline cases are found by
    # reading a run's answers (task 5.4) and freezing it would price every
    # discovery at a fresh run. The two lists therefore behave differently, which
    # is a wart accepted deliberately and recorded in the ADR.
    #
    # A question may rest on this list **alone**, and that is the third state the
    # set needs: a false premise. "What is the volume of the nucleus of an E. coli
    # cell?" has no expected entry, because nothing records the volume of a thing
    # that does not exist, and it is not unsupported either, because the corpus
    # holds the nucleoid. Marking it unsupported would score a correct answer --
    # cite the nucleoid, say the premise does not hold -- as a failure to decline.
    admissible_entries: tuple[int, ...] = ()
    unsupported: bool = False
    # The question this one follows, asked in that question's session.
    follows: str | None = None
    # What the question demands of the agent. A closed vocabulary, and `Tier` says
    # why -- it is compared against the same tier in an earlier run.
    tier: Tier = Tier.BASIC
    # What the question exercises -- a comparison, a conversion, an unsupported ask.
    # Free-form on purpose, unlike the tier above: the report merely groups by a
    # tag, and a fixed vocabulary here would have to be widened by whoever adds the
    # next kind of question, which is the moment they are least likely to touch
    # this file.
    tags: tuple[str, ...] = ()
    notes: str = ""

    def __post_init__(self) -> None:
        if not self.question_id or not self.question:
            raise QuestionSetError("A question needs an identifier and a question.")
        if not self.asked_properties or not self.asked_organisms:
            raise QuestionSetError(
                f"{self.question_id!r} records no asked property or organism; "
                f"whether the agent looked for them could not be scored."
            )
        if self.unsupported and self.expected_entries:
            raise QuestionSetError(
                f"{self.question_id!r} is marked unsupported and names expected entries."
            )
        if self.unsupported and self.admissible_entries:
            raise QuestionSetError(
                f"{self.question_id!r} is marked unsupported and names admissible entries."
            )
        both = set(self.expected_entries) & set(self.admissible_entries)
        if both:
            raise QuestionSetError(
                f"{self.question_id!r} names {sorted(both)} as both expected and "
                f"admissible. The lists mean opposite things about a missing citation "
                f"-- expected is a miss, admissible is not -- so an entry in both makes "
                f"the score depend on which list is read first."
            )
        if not self.unsupported and not (self.expected_entries or self.admissible_entries):
            raise QuestionSetError(
                f"{self.question_id!r} names neither expected nor admissible entries and "
                f"is not marked unsupported; it would score as citing 0 of 0, which reads "
                f"as a pass."
            )
        if self.follows == self.question_id:
            raise QuestionSetError(f"{self.question_id!r} follows itself.")


class EntryShape(StrEnum):
    """What an expected entry does and does not carry, derived from the corpus.

    Never recorded in the set. A shape written by hand is a claim about the corpus
    made at the time the question was written, and it goes stale the first time the
    corpus is rebuilt -- silently, since nothing would compare the two.
    """

    COMPLETE = "complete"
    NO_SCALAR = "no scalar value"
    # A blank unit and an unrecognised one are not the same thing, and this shape
    # covers both: what the evaluation needs to know is whether a dimension can be
    # put on the figure at all, and in neither case can it. Which of the two it was
    # is in the entry.
    NO_CLASSIFIED_UNIT = "no classified unit"
    FUSED_RANGE = "fused range"
    NO_METHOD = "no measurement method"
    HEDGED_RANGE = "hedged range"


def shapes_of(entry: Entry) -> frozenset[EntryShape]:
    """The shapes an entry carries: its deficiencies, or `COMPLETE` if it has none.

    Not one shape per entry. An entry can lack a scalar *and* a method, and
    reporting only the first found would hide the second from every figure given
    per shape.
    """
    lacking = set()
    if entry.value is None:
        lacking.add(EntryShape.NO_SCALAR)
    if dimension(entry.units) is None:
        lacking.add(EntryShape.NO_CLASSIFIED_UNIT)
    if entry.range_fused:
        lacking.add(EntryShape.FUSED_RANGE)
    if not entry.measurement_method.strip():
        lacking.add(EntryShape.NO_METHOD)
    # All three flags, not `range_qualified` alone. `corpus.py` reads the three as
    # independent booleans defaulting to False, and it is the *ingester* that
    # derives the general flag from the two specific ones -- so a corpus carrying
    # `range_approximate` without `range_qualified` loads perfectly well, and
    # reading only the general flag files a value of "~20" as a complete entry with
    # an exact number. That is the expensive direction: `COMPLETE` is the claim a
    # value check would be strict about.
    if entry.range_qualified or entry.range_approximate or entry.range_one_sided:
        lacking.add(EntryShape.HEDGED_RANGE)
    return frozenset(lacking) if lacking else frozenset({EntryShape.COMPLETE})


def load_question_set(
    path: str | Path | None, entries: tuple[Entry, ...] | None
) -> tuple[Question, ...]:
    """Read and validate a question set, against the corpus when one is supplied.

    `entries` has no default, deliberately. The evaluation driver always has a
    corpus -- the agent cannot answer without one -- so it must not be able to skip
    the corpus checks by leaving an argument off. Passing `None` is a
    structure-only read and a decision the caller makes out loud; the command that
    does it says in its output what it did not check.

    The refusal to run without a set lives here rather than in the command, so a
    harness, a test or a later driver calling this gets it too.
    """
    if not path:
        raise QuestionSetError(
            "No question set supplied. The evaluation scores answers against a set "
            "of questions that record the entries which should support them; there "
            "is no default set, because a set the system under test produced is one "
            "it would pass. Pass the path to a question set."
        )
    file = Path(path)
    if not file.is_file():
        raise QuestionSetError(f"No question set file at {file}.")

    # Each question is kept beside where it was read from, so a rule that needs the
    # whole set can still point at a line. Counting questions instead would name the
    # third question as "3" in a file whose third question is on line 5.
    located: list[tuple[str, Question]] = []
    # `utf-8-sig` rather than `utf-8`: a set is edited by hand, and the commonest
    # editors on Windows write a byte-order mark. It reads plain UTF-8 identically,
    # so this costs nothing and stops "Unexpected UTF-8 BOM" from being the first
    # thing a colleague sees. Explicit rather than the locale default because a set
    # holds organism names and units, and a micro sign read under a non-UTF-8
    # locale fails on their machine and not on ours.
    with file.open(encoding="utf-8-sig") as handle:
        for number, line in enumerate(handle, start=1):
            line = line.strip()
            if not line:
                continue
            where = f"{file}:{number}"
            try:
                raw = json.loads(line)
            except json.JSONDecodeError as exc:
                raise QuestionSetError(f"{where} is not valid JSON: {exc}") from exc
            located.append((where, _question(raw, where)))

    if not located:
        raise QuestionSetError(f"{file} holds no questions.")
    _check_the_set(located)
    questions = tuple(question for _, question in located)
    if entries is not None:
        check_against_corpus(questions, entries)
    return questions


# Plural, matching the field names on `Question`: the value may be a string or a
# list, and a key that differs from the attribute it fills is how a later author
# comes to write one and read the other.
_REQUIRED = ("question_id", "question", "asked_properties", "asked_organisms")
_OPTIONAL = (
    "expected_entries",
    "admissible_entries",
    "tier",
    "unsupported",
    "follows",
    "tags",
    "notes",
)


def _question(raw: object, where: str) -> Question:
    if not isinstance(raw, dict):
        raise QuestionSetError(f"{where} is not a JSON object.")

    unknown = sorted(set(raw) - set(_REQUIRED) - set(_OPTIONAL))
    if unknown:
        raise QuestionSetError(
            f"{where} carries {unknown}, which this reader does not know. A "
            f"misspelled key would otherwise be read as absent and scored as such. "
            f"Known keys: {sorted(_REQUIRED + _OPTIONAL)}."
        )
    missing = [key for key in _REQUIRED if key not in raw]
    if missing:
        raise QuestionSetError(f"{where} is missing {missing}.")

    identifier = _text(raw["question_id"], "question_id", where)
    expected = _entry_identifiers(raw.get("expected_entries", []), where)
    admissible = _entry_identifiers(
        raw.get("admissible_entries", []), where, key="admissible_entries"
    )
    unsupported = _boolean(raw.get("unsupported", False), "unsupported", where)

    # Each direction of the disagreement is its own sentence: they are different
    # mistakes and the fix for one is not the fix for the other. `Question` refuses
    # both as well; these run first because they can name the line and the flag.
    if unsupported and admissible:
        raise QuestionSetError(
            f"{where} is marked unsupported but names admissible entries {list(admissible)}. "
            f"An admissible entry is one a citation may rest on; an unsupported question "
            f"has none."
        )
    if unsupported and expected:
        raise QuestionSetError(
            f"{where} is marked unsupported but names expected entries {list(expected)}. "
            f"An unsupported question is one the corpus cannot answer; if these entries "
            f"do support it, drop the flag."
        )
    if not unsupported and not (expected or admissible):
        raise QuestionSetError(
            f"{where} names neither expected nor admissible entries and is not marked "
            f"unsupported. Nothing could be scored for it: add the entries that should "
            f"support the answer, or mark it unsupported."
        )

    follows = raw.get("follows")
    if follows is not None:
        follows = _text(follows, "follows", where)
        if follows == identifier:
            raise QuestionSetError(f"{where} follows itself.")

    return Question(
        question_id=identifier,
        tier=_tier(raw.get("tier", Tier.BASIC), where),
        question=_text(raw["question"], "question", where),
        asked_properties=_terms(raw["asked_properties"], "asked_properties", where),
        asked_organisms=_terms(raw["asked_organisms"], "asked_organisms", where),
        expected_entries=expected,
        admissible_entries=admissible,
        unsupported=unsupported,
        follows=follows,
        tags=_tags(raw.get("tags", []), where),
        notes=_text(raw.get("notes", ""), "notes", where, allow_empty=True),
    )


def _text(value: object, key: str, where: str, *, allow_empty: bool = False) -> str:
    if not isinstance(value, str):
        raise QuestionSetError(f"{where}: {key} must be a string, not {type(value).__name__}.")
    # Stripped, so a padded identifier matches the `follows` naming it and a padded
    # organism term reaches the repository's resolution as itself.
    text = value.strip()
    if not allow_empty and not text:
        raise QuestionSetError(f"{where}: {key} is empty.")
    return text


def _terms(value: object, key: str, where: str) -> tuple[str, ...]:
    """One term or several: a string, or a list of them for a comparison."""
    items = value if isinstance(value, list) else [value]
    if not items:
        raise QuestionSetError(f"{where}: {key} is empty.")
    terms = tuple(_text(item, key, where) for item in items)
    repeated = sorted({term for term in terms if terms.count(term) > 1})
    if repeated:
        raise QuestionSetError(f"{where}: {key} repeats {repeated}.")
    return terms


def _boolean(value: object, key: str, where: str) -> bool:
    if not isinstance(value, bool):
        raise QuestionSetError(f"{where}: {key} must be true or false.")
    return value


def _entry_identifiers(value: object, where: str, key: str = "expected_entries") -> tuple[int, ...]:
    """`key` names the list in every message: two lists share this reader now, and
    a refusal that always said "expected_entries" would send a reader to the wrong
    one."""
    if not isinstance(value, list):
        raise QuestionSetError(f"{where}: {key} must be a list.")
    identifiers = []
    for item in value:
        # `isinstance(True, int)` is true, so booleans are excluded explicitly --
        # `[true]` would otherwise become entry 1.
        if isinstance(item, bool) or not isinstance(item, int):
            raise QuestionSetError(
                f"{where}: {key} holds {item!r}. Entry identifiers are "
                f"written as bare integers, the way the corpus and the citation form "
                f"carry them; a quoted one would never match a citation."
            )
        identifiers.append(item)
    duplicates = sorted({i for i in identifiers if identifiers.count(i) > 1})
    if duplicates:
        raise QuestionSetError(f"{where}: {key} repeats {duplicates}.")
    return tuple(identifiers)


def _tier(value: object, where: str) -> Tier:
    """Refused by name against the closed vocabulary, with the choices listed.

    A tier the reader does not know cannot be defaulted: silently filing a
    mistyped "compund" question under `basic` moves it into the bucket whose whole
    purpose is to stay honest about the simple questions.
    """
    if isinstance(value, Tier):
        return value
    if not isinstance(value, str):
        raise QuestionSetError(f"{where}: tier must be a string, not {type(value).__name__}.")
    try:
        return Tier(value.strip().lower())
    except ValueError:
        raise QuestionSetError(
            f"{where}: tier {value!r} is not one of {[str(t) for t in Tier]}. The "
            f"report compares a tier against the same tier in an earlier run, so an "
            f"unknown one would open a bucket of its own rather than join a figure."
        ) from None


def _tags(value: object, where: str) -> tuple[str, ...]:
    """Tags, stripped and distinct, because the report groups its figures by them.

    A repeat counts one question twice in its own bucket, and two tags differing
    only in case make two buckets a reader then compares against each other -- the
    same reasoning that deduplicates expected entries. The vocabulary is free-form,
    so there is nothing to check a tag *against*; being distinct needs no
    vocabulary.
    """
    if not isinstance(value, list):
        raise QuestionSetError(f"{where}: tags must be a list.")
    kept: list[str] = []
    seen: dict[str, str] = {}
    for tag in value:
        text = _text(tag, "tag", where)
        folded = text.casefold()
        if folded in seen:
            if seen[folded] == text:
                raise QuestionSetError(f"{where}: tags repeat {text!r}.")
            raise QuestionSetError(
                f"{where}: tags {seen[folded]!r} and {text!r} differ only in case. The "
                f"report groups by tag, so these would be two buckets nobody meant; "
                f"pick one spelling."
            )
        seen[folded] = text
        kept.append(text)
    return tuple(kept)


def _check_the_set(located: list[tuple[str, Question]]) -> None:
    """The rules that need the whole set: unique identifiers, and real parents."""
    seen: dict[str, str] = {}
    for where, question in located:
        if question.question_id in seen:
            raise QuestionSetError(
                f"Question id {question.question_id!r} appears twice, at "
                f"{seen[question.question_id]} and {where}. Results are keyed by it, "
                f"so a repeat would overwrite a result on resumption."
            )
        seen[question.question_id] = where

    by_id = {question.question_id: question for _, question in located}
    # Every parent is checked to exist before any chain is walked. Checking each
    # question's own parent as the walk reached it left the walk free to step
    # through a *grandparent* nobody had checked: a set whose second question
    # followed something absent raised `KeyError` from the first question's walk,
    # and the command reported that as a traceback rather than as a sentence.
    # Whether it happened at all depended on the order of the lines.
    for where, question in located:
        if question.follows is not None and question.follows not in by_id:
            raise QuestionSetError(
                f"{where}: {question.question_id!r} follows {question.follows!r}, which "
                f"the set does not contain. A follow-up is asked in its parent's "
                f"session, and there would be no session to ask it in."
            )

    for where, question in located:
        # A cycle would have no session to start from either, and walking the chain
        # to find the parent's result on resumption would not terminate.
        walked = [question.question_id]
        parent = question.follows
        while parent is not None:
            if parent in walked:
                # From the repeated identifier onward, not the whole walk: where A
                # follows B follows C follows B, the cycle is B and C, and naming A
                # in it sends the reader to the one question that is fine.
                cycle = walked[walked.index(parent) :]
                raise QuestionSetError(
                    f"{where}: {question.question_id!r} leads into a cycle of "
                    f"follow-ups ({cycle}). No question in it could be asked first."
                )
            walked.append(parent)
            parent = by_id[parent].follows


def check_against_corpus(questions: tuple[Question, ...], entries: tuple[Entry, ...]) -> None:
    """Refuse a set the corpus contradicts, reporting every problem at once.

    Three different failures, and a person fixing the set wants all of them
    together: an identifier the corpus does not hold, a shape no question
    exercises, and an unsupported flag on a question the corpus can answer.

    **Reported together rather than one at a time, and that is not only
    convenience.** Raising on the first found hid the third behind the second: a
    set of one unsupported question has no expected entries, so it always failed
    the shape rule, and the flag was never checked at all. An ordering that decides
    which problem a person is allowed to see is a bug in the checker.
    """
    held = {entry.entry_id: entry for entry in entries}
    problems: list[str] = []

    absent = {
        question.question_id: sorted(set(question.expected_entries) - set(held))
        for question in questions
        if set(question.expected_entries) - set(held)
    }
    if absent:
        listed = "; ".join(f"{qid} expects {ids}" for qid, ids in sorted(absent.items()))
        problems.append(
            f"The corpus does not hold every expected entry: {listed}. Either the set "
            f"predates this corpus or an identifier is wrong; nothing can be scored "
            f"against an entry that is not there."
        )

    # Checked with the same force as the expected list, and for the same reason: an
    # admissible identifier the corpus does not hold stops a citation being called
    # unexpected only for an entry nothing can cite, so the list silently does
    # nothing. Reported apart because the fix differs -- an expected entry that has
    # gone means the question lost support, an admissible one means the exemption
    # lapsed.
    unheld = {
        question.question_id: sorted(set(question.admissible_entries) - set(held))
        for question in questions
        if set(question.admissible_entries) - set(held)
    }
    if unheld:
        listed = "; ".join(f"{qid} admits {ids}" for qid, ids in sorted(unheld.items()))
        problems.append(
            f"The corpus does not hold every admissible entry: {listed}. An admissible "
            f"entry exempts a citation from being reported as unexpected, and one the "
            f"corpus lacks exempts nothing."
        )

    # Only the identifiers the corpus holds: the absent ones are already reported,
    # and looking their shapes up would raise instead of adding to the list.
    present: set[EntryShape] = set()
    for question in questions:
        for identifier in question.expected_entries:
            if identifier in held:
                present |= shapes_of(held[identifier])
    missing = [shape for shape in EntryShape if shape not in present]
    if missing:
        problems.append(
            f"No question's expected entries carry these shapes: "
            f"{[str(shape) for shape in missing]}. The report gives its figures per "
            f"shape, and a shape absent from the set is a figure nobody can read. Add "
            f"a question whose expected entries carry each."
        )

    answerable = _unsupported_the_corpus_can_answer(questions, entries)
    if answerable:
        listed = "; ".join(
            f"{qid} could be answered from {ids}" for qid, ids in sorted(answerable.items())
        )
        problems.append(
            f"A question marked unsupported is one the corpus can answer: {listed}. "
            f"This is the most expensive mistake a set can carry: the agent answers "
            f"it correctly and cites, and that is then scored as a fabrication -- the "
            f"evaluation's most-read figure, wrong for the one reason no reader would "
            f"suspect. Drop the flag and record the entries, or narrow what the "
            f"question asks."
        )

    if problems:
        raise QuestionSetError("\n\n".join(problems))


def _unsupported_the_corpus_can_answer(
    questions: tuple[Question, ...], entries: tuple[Entry, ...]
) -> dict[str, list[int]]:
    """Unsupported questions the corpus does hold entries for. Task 4.11.

    Resolved the way the corpus's own search resolves, so an abbreviated binomial
    counts -- the same public methods the evaluation's asked-terms score uses,
    rather than a second rule that would drift from them.

    **The conjunction, not either half.** A question asking for E. coli's nuclear
    volume resolves to a real property and a real organism and is still
    unanswerable, because no entry carries both. Refusing on either half alone
    would reject exactly the questions worth having in the set.

    **Which direction is expensive.** A question wrongly refused here costs one
    line of the set, edited by the person who is already looking at the file. A
    question wrongly accepted costs the headline figure of the whole evaluation.
    So the refusal absorbs the uncertainty, and task 4.10 counts both directions
    against the first real run.
    """
    # Built here rather than taken as an argument: the resolution has to be the
    # repository's, and a caller holding entries should not have to build one to
    # validate a set. It is an index over the corpus, built once per check.
    repo = CorpusRepository(entries)
    answerable: dict[str, list[int]] = {}
    for question in questions:
        if not question.unsupported:
            continue
        organisms = {
            stored for term in question.asked_organisms for stored in repo.resolve_organism(term)
        }
        properties = {
            stored for term in question.asked_properties for stored in repo.resolve_property(term)
        }
        if not organisms or not properties:
            continue
        found = [
            entry.entry_id
            for entry in entries
            if entry.organism in organisms and entry.property in properties
        ]
        if found:
            answerable[question.question_id] = sorted(found)[:5]
    return answerable
