"""The question set: what is asked, which entries should support it, what it exercises.

One JSON object per line (ADR-0220), read by the evaluation harness and never
generated by the system under test -- a set the agent wrote is a set the agent
passes. The file is the reference the whole evaluation is scored against, so the
loader is strict rather than forgiving: a set that loads is one every score can be
computed from, and a set that cannot be is a message naming the line and the fix.

**Which direction the strictness runs, and why.** Every rule here refuses a set
rather than repairing it, because each repair would be silent at exactly the moment
it mattered. An unknown key is rejected, not ignored: `expected_entires` ignored
leaves a question with no expected entries, which scores as the agent citing
nothing expected -- a perfect run reported as a total failure, or the reverse, with
nothing anywhere saying why. A quoted identifier is rejected rather than coerced,
because `"113525"` never equals the `113525` the citation parser produces and the
comparison would fail forever, quietly. The cost of the strict direction is a
person editing one line; the cost of the lenient one is a figure nobody can trust.

Entry identifiers are integers here because they are integers everywhere else --
`Entry.entry_id`, `citations()` and `AnswerEntries.cited` all carry `int` -- and a
set that recorded them as strings would compare unequal to every citation.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from enum import StrEnum
from pathlib import Path

from .corpus import Entry
from .units import dimension


class QuestionSetError(Exception):
    """A question set that cannot be scored against, and what to do about it."""


@dataclass(frozen=True)
class Question:
    """One question, its expected support, and what it is in the set to exercise."""

    question_id: str
    question: str
    # In the corpus's own vocabulary, so that whether the agent looked for them can
    # be scored against the repository's own resolution rather than against a
    # paraphrase. Required even for an unsupported question: the terms are what the
    # question asks about, and that they resolve to nothing is the point of it.
    asked_property: str
    asked_organism: str
    expected_entries: tuple[int, ...] = ()
    unsupported: bool = False
    # The question this one follows, asked in that question's session. A chain, not
    # a tree of arbitrary depth in practice, but nothing here limits the depth.
    follows: str | None = None
    # What the question exercises -- a comparison, a conversion, an unsupported ask.
    # Free-form on purpose: the report gives its figures per tag, and a fixed
    # vocabulary here would have to be widened by whoever adds the next kind of
    # question, which is the moment they are least likely to touch this file.
    tags: tuple[str, ...] = ()
    notes: str = ""


class EntryShape(StrEnum):
    """What an expected entry does and does not carry, derived from the corpus.

    Never recorded in the set. A shape written by hand is a claim about the corpus
    made at the time the question was written, and it goes stale the first time the
    corpus is rebuilt -- silently, since nothing would compare the two.
    """

    COMPLETE = "complete"
    NO_SCALAR = "no scalar value"
    # A blank unit and an unrecognised one are not the same thing, and this shape
    # covers both: what the evaluation needs to know is whether a dimension can be
    # put on the figure at all, and in neither case can it. Which of the two it was
    # is in the entry.
    NO_CLASSIFIED_UNIT = "no classified unit"
    FUSED_RANGE = "fused range"
    NO_METHOD = "no measurement method"
    HEDGED_RANGE = "hedged range"


def shapes_of(entry: Entry) -> frozenset[EntryShape]:
    """The shapes an entry carries: its deficiencies, or `COMPLETE` if it has none.

    Not one shape per entry. An entry can lack a scalar *and* a method, and
    reporting only the first found would hide the second from every figure given
    per shape.
    """
    lacking = set()
    if entry.value is None:
        lacking.add(EntryShape.NO_SCALAR)
    if dimension(entry.units) is None:
        lacking.add(EntryShape.NO_CLASSIFIED_UNIT)
    if entry.range_fused:
        lacking.add(EntryShape.FUSED_RANGE)
    if not entry.measurement_method.strip():
        lacking.add(EntryShape.NO_METHOD)
    if entry.range_qualified:
        lacking.add(EntryShape.HEDGED_RANGE)
    return frozenset(lacking) if lacking else frozenset({EntryShape.COMPLETE})


def load_question_set(path: str | Path | None) -> tuple[Question, ...]:
    """Read and validate a question set. Structure only; see `check_against_corpus`.

    The refusal to run without a set lives here rather than in the command, so a
    harness, a test or a later driver calling this gets it too.
    """
    if not path:
        raise QuestionSetError(
            "No question set supplied. The evaluation scores answers against a set "
            "of questions that record the entries which should support them; there "
            "is no default set, because a set the system under test produced is one "
            "it would pass. Pass the path to a question set."
        )
    file = Path(path)
    if not file.is_file():
        raise QuestionSetError(f"No question set file at {file}.")

    # Each question is kept beside where it was read from, so a rule that needs the
    # whole set can still point at a line. Counting questions instead would name the
    # third question as "3" in a file whose third question is on line 5.
    located: list[tuple[str, Question]] = []
    # Explicit, not the locale default: a question set holds organism names and
    # units, and "μm" read under a non-UTF-8 locale fails on a colleague's machine
    # and not on ours.
    with file.open(encoding="utf-8") as handle:
        for number, line in enumerate(handle, start=1):
            line = line.strip()
            if not line:
                continue
            where = f"{file}:{number}"
            try:
                raw = json.loads(line)
            except json.JSONDecodeError as exc:
                raise QuestionSetError(f"{where} is not valid JSON: {exc}") from exc
            located.append((where, _question(raw, where)))

    if not located:
        raise QuestionSetError(f"{file} holds no questions.")
    _check_the_set(located)
    return tuple(question for _, question in located)


_REQUIRED = ("question_id", "question", "asked_property", "asked_organism")
_OPTIONAL = ("expected_entries", "unsupported", "follows", "tags", "notes")


def _question(raw: object, where: str) -> Question:
    if not isinstance(raw, dict):
        raise QuestionSetError(f"{where} is not a JSON object.")

    unknown = sorted(set(raw) - set(_REQUIRED) - set(_OPTIONAL))
    if unknown:
        raise QuestionSetError(
            f"{where} carries {unknown}, which this reader does not know. A "
            f"misspelled key would otherwise be read as absent and scored as such. "
            f"Known keys: {sorted(_REQUIRED + _OPTIONAL)}."
        )
    missing = [key for key in _REQUIRED if key not in raw]
    if missing:
        raise QuestionSetError(f"{where} is missing {missing}.")

    values = {key: _text(raw[key], key, where) for key in _REQUIRED}
    expected = _entry_identifiers(raw.get("expected_entries", []), where)
    unsupported = _boolean(raw.get("unsupported", False), "unsupported", where)

    # Each direction of the disagreement is its own sentence: they are different
    # mistakes and the fix for one is not the fix for the other.
    if unsupported and expected:
        raise QuestionSetError(
            f"{where} is marked unsupported but names expected entries {list(expected)}. "
            f"An unsupported question is one the corpus cannot answer; if these entries "
            f"do support it, drop the flag."
        )
    if not unsupported and not expected:
        raise QuestionSetError(
            f"{where} names no expected entries and is not marked unsupported. "
            f"Nothing could be scored for it: add the entries that should support "
            f"the answer, or mark it unsupported."
        )

    follows = raw.get("follows")
    if follows is not None:
        follows = _text(follows, "follows", where)
        if follows == values["question_id"]:
            raise QuestionSetError(f"{where} follows itself.")

    return Question(
        question_id=values["question_id"],
        question=values["question"],
        asked_property=values["asked_property"],
        asked_organism=values["asked_organism"],
        expected_entries=expected,
        unsupported=unsupported,
        follows=follows,
        tags=_tags(raw.get("tags", []), where),
        notes=_text(raw.get("notes", ""), "notes", where, allow_empty=True),
    )


def _text(value: object, key: str, where: str, *, allow_empty: bool = False) -> str:
    if not isinstance(value, str):
        raise QuestionSetError(f"{where}: {key} must be a string, not {type(value).__name__}.")
    if not allow_empty and not value.strip():
        raise QuestionSetError(f"{where}: {key} is empty.")
    return value


def _boolean(value: object, key: str, where: str) -> bool:
    if not isinstance(value, bool):
        raise QuestionSetError(f"{where}: {key} must be true or false.")
    return value


def _entry_identifiers(value: object, where: str) -> tuple[int, ...]:
    if not isinstance(value, list):
        raise QuestionSetError(f"{where}: expected_entries must be a list.")
    identifiers = []
    for item in value:
        # `isinstance(True, int)` is true, so booleans are excluded explicitly --
        # `[true]` would otherwise become entry 1.
        if isinstance(item, bool) or not isinstance(item, int):
            raise QuestionSetError(
                f"{where}: expected_entries holds {item!r}. Entry identifiers are "
                f"written as bare integers, the way the corpus and the citation form "
                f"carry them; a quoted one would never match a citation."
            )
        identifiers.append(item)
    duplicates = sorted({i for i in identifiers if identifiers.count(i) > 1})
    if duplicates:
        raise QuestionSetError(f"{where}: expected_entries repeats {duplicates}.")
    return tuple(identifiers)


def _tags(value: object, where: str) -> tuple[str, ...]:
    if not isinstance(value, list):
        raise QuestionSetError(f"{where}: tags must be a list.")
    return tuple(_text(tag, "tag", where) for tag in value)


def _check_the_set(located: list[tuple[str, Question]]) -> None:
    """The rules that need the whole set: unique identifiers, and real parents."""
    seen: dict[str, str] = {}
    for where, question in located:
        if question.question_id in seen:
            raise QuestionSetError(
                f"Question id {question.question_id!r} appears twice, at "
                f"{seen[question.question_id]} and {where}. Results are keyed by it, "
                f"so a repeat would overwrite a result on resumption."
            )
        seen[question.question_id] = where

    by_id = {question.question_id: question for _, question in located}
    for where, question in located:
        if question.follows is None:
            continue
        if question.follows not in by_id:
            raise QuestionSetError(
                f"{where}: {question.question_id!r} follows {question.follows!r}, which "
                f"the set does not contain. A follow-up is asked in its parent's "
                f"session, and there would be no session to ask it in."
            )
        # A cycle would have no session to start from either, and walking the chain
        # to find the parent's result on resumption would not terminate.
        walked = {question.question_id}
        parent = question.follows
        while parent is not None:
            if parent in walked:
                raise QuestionSetError(
                    f"{where}: {question.question_id!r} is in a cycle of follow-ups "
                    f"({sorted(walked)}). No question in it could be asked first."
                )
            walked.add(parent)
            parent = by_id[parent].follows


def check_against_corpus(questions: tuple[Question, ...], entries: tuple[Entry, ...]) -> None:
    """Refuse a set whose expected entries are absent, or whose shapes are partial.

    Two different failures, reported together because a person fixing the set wants
    both at once: an identifier the corpus does not hold (a stale set, or a typo),
    and a shape no question in the set exercises.

    The shape rule is what stops a set from measuring the happy path alone. Most of
    the corpus is incomplete in at least one way, so a set drawn only from complete
    entries says nothing about the behaviour most questions will actually meet.
    """
    held = {entry.entry_id: entry for entry in entries}
    absent = {
        question.question_id: sorted(set(question.expected_entries) - set(held))
        for question in questions
        if set(question.expected_entries) - set(held)
    }
    if absent:
        listed = "; ".join(f"{qid} expects {ids}" for qid, ids in sorted(absent.items()))
        raise QuestionSetError(
            f"The corpus does not hold every expected entry: {listed}. Either the set "
            f"predates this corpus or an identifier is wrong; nothing can be scored "
            f"against an entry that is not there."
        )

    present: set[EntryShape] = set()
    for question in questions:
        for identifier in question.expected_entries:
            present |= shapes_of(held[identifier])
    missing = [shape for shape in EntryShape if shape not in present]
    if missing:
        raise QuestionSetError(
            f"No question's expected entries carry these shapes: "
            f"{[str(shape) for shape in missing]}. The report gives its figures per "
            f"shape, and a shape absent from the set is a figure nobody can read. Add "
            f"a question whose expected entries carry each."
        )
